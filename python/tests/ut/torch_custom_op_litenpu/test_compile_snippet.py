def _reimport_and_rebuild(snippet, kernel_name, infer_shape_name, infer_dtype_name, tmp_path):
    modname = kernel_name + "_regen"
    (tmp_path / (modname + ".py")).write_text(snippet)
    sys.path.insert(0, str(tmp_path))
    try:
        mod = importlib.import_module(modname)
        return kernel_snippet.build_kernel_compile_snippet(
            mode="jit_kernel", jit_kernel_func=getattr(mod, kernel_name),
            infer_shape_func=getattr(mod, infer_shape_name),
            infer_dtype_func=getattr(mod, infer_dtype_name), n_inputs=2,
        )
    finally:
        sys.path.remove(str(tmp_path))
        sys.modules.pop(modname, None)


@pytest.mark.parametrize(("mod", "kernel", "infer_shape", "infer_dtype", "extra_token"), [
    (samples, "direct_kernel_local_import", "add_infer_shape", "add_infer_dtype", None),
    (pep563_direct, "pep563_direct_add_kernel", "pep563_infer_shape", "pep563_infer_dtype", None),
    (samples, "direct_add_kernel_erased", "infer_shape_local_import", "add_infer_dtype", "import math\n"),
])
def test_true_idempotence(mod, kernel, infer_shape, infer_dtype, extra_token, tmp_path):
    """regen(regen(x)) == regen(x) byte-identically: a hoisted import becomes a module-scope header
    import on re-trace, so the hoist-and-delete is a fixed point with no churn."""
    s1 = kernel_snippet.build_kernel_compile_snippet(
        mode="jit_kernel", jit_kernel_func=getattr(mod, kernel),
        infer_shape_func=getattr(mod, infer_shape),
        infer_dtype_func=getattr(mod, infer_dtype), n_inputs=2,
    )
    if extra_token is not None:
        assert extra_token in s1
    s2 = _reimport_and_rebuild(s1, kernel, infer_shape, infer_dtype, tmp_path)
    assert s1 == s2


