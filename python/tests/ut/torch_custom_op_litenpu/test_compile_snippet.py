# ---- the emitted decorator is always forced to SIM ---------------------------------------------------

def _decorator_line(snippet: str) -> str:
    """The ``@pypto.frontend.jit(...)`` line(s) of the emitted DIRECT kernel (up to its ``def``)."""
    lines = snippet.splitlines()
    start = next(i for i, ln in enumerate(lines) if "@pypto.frontend.jit" in ln)
    end = next(i for i, ln in enumerate(lines[start:], start) if ln.lstrip().startswith("def "))
    return "\n".join(lines[start:end])


def test_direct_snippet_forces_sim_decorator():
    # SOURCE kernel is decorated run_mode=NPU; the deploy snippet decorator must be forced to SIM.
    snippet = _direct_snippet(samples.direct_add_kernel_npu_source)
    deco = _decorator_line(snippet)
    assert "pypto.RunMode.SIM" in deco
    assert "RunMode.NPU" not in deco
    # A body line that references RunMode.NPU (not the decorator) must survive untouched.
    assert "_unused = pypto.RunMode.NPU" in snippet


# The decorator form matrix: forced or injected SIM, at the string level.

_BODY = "def add_kernel(a, b, c):\n    c.move(a + b)\n"


@pytest.mark.parametrize("deco", [
    '@pypto.frontend.jit(runtime_options={"run_mode": pypto.RunMode.NPU})\n',   # present NPU -> rewritten
    '@pypto.frontend.jit(runtime_options={"run_mode": pypto.RunMode.SIM})\n',   # present SIM -> unchanged
    '@pypto.frontend.jit\n',                                                    # bare, no parens -> injected
    '@pypto.frontend.jit()\n',                                                  # empty parens -> injected
    '@pypto.frontend.jit(codegen_options={"foo": 1})\n',                        # other kwargs -> injected
    '@pypto.frontend.jit(runtime_options={"foo": 1})\n',                        # runtime_options w/o run_mode
    '@pypto.frontend.jit(\n    codegen_options={"foo": 1},\n)\n',               # multi-line -> injected
    '@pypto.frontend.jit(codegen_options={"foo": 1})  # trailing comment\n',    # trailing comment -> injected
])
def test_force_sim_decorator_form_matrix(deco):
    out = kernel_snippet._force_sim_in_decorator(deco + _BODY)
    deco_span = out.split("def ", 1)[0]
    assert "pypto.RunMode.SIM" in deco_span
    assert "RunMode.NPU" not in deco_span
    # The kernel BODY must be preserved verbatim (only the decorator span is touched).
    assert out.endswith(_BODY)


def test_force_sim_decorator_non_literal_runtime_options_raises():
    # runtime_options=<NAME> (not an inline dict): can't inject a run_mode key safely -> clear error.
    block = '@pypto.frontend.jit(runtime_options=MY_OPTS)\n' + _BODY
    with pytest.raises(ValueError, match="runtime_options"):
        kernel_snippet._force_sim_in_decorator(block)
