def _factory_snippet(create_kernel_func, kernel_body_func=None) -> str:
    return kernel_snippet.build_kernel_compile_snippet(
        create_kernel_func=create_kernel_func,
        infer_shape_func=samples.add_infer_shape,
        infer_dtype_func=samples.add_infer_dtype,
        n_inputs=2,
        kernel_body_func=kernel_body_func,
    )


def _snippet() -> str:
    return _factory_snippet(samples.create_add_kernel, samples.add_kernel_body)


