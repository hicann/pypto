"""Unit tests for the embedded compile-snippet generator (kernel extraction).

Layers:

* ``test_compile_snippet_assembles``, backend-free: valid Python, decorated functions kept under their
  original names, nested ``@pypto.frontend.jit`` kept, ``__pypto_compile`` exposed.
* the packing tests: which helper defs, constants and hoisted imports a snippet carries, across the
  factory, pinned/erased DIRECT, dotted-helper and PEP-563 forms.
* the golden suite: every case in ``GOLDEN_CASES`` is pinned whole-text against a checked-in file in
  ``test_compile_snippet_data/``, regenerated by that directory's ``render.py``.
* the fixed-point tests: a helper-free snippet is byte-identical across builds, and
  ``regen(regen(x)) == regen(x)`` once a hoisted import has become a header import.
* the emitted-decorator tests: the deployed ``@pypto.frontend.jit`` always reads
  ``run_mode": pypto.RunMode.SIM``, across every decorator spelling.
* ``test_compile_snippet_builds_real_kernel``: a real JIT build from the materialized snippet,
  asserting the ``.o`` and the ``*_aiv.json`` sidecar.
"""

