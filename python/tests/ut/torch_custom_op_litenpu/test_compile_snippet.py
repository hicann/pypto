    assert _direct_snippet(samples.direct_add_kernel_erased) == _direct_snippet(samples.direct_add_kernel_erased)
    # And the kernel body is emitted verbatim (no canonical mangling of a helper-free kernel).
    snippet = _direct_snippet(samples.direct_add_kernel_erased)
