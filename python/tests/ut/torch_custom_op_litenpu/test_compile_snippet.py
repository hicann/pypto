def test_direct_dotted_helper_snippet_packs_flattened_helpers(tmp_path):
    """A module-qualified-reference direct kernel (``pkg.mod.fn(...)``) packs its helpers under the
    flattened ``pkg__mod__fn`` def, rewrites the kernel body call sites to the flat name, and does not
    leak the helper package name. Materializing and importing it then resolves the flattened names at
    module scope with no NameError, and the kernel round-trips as a JitCallableWrapper."""
    snippet = _direct_snippet(samples.direct_dotted_helper_kernel)
    compile(snippet, "<compile_snippet>", "exec")
