        # (not a plain callable), so assert only that the flattened name resolves (no NameError).
        assert getattr(mod, "sample_helper_pkg__compute__tile_helper")() == (1, 4, 1, 64)
        assert getattr(mod, "sample_helper_pkg__compute__add_into") is not None
