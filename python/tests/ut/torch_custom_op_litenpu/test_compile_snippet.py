# ---- the golden suite ---------------------------------------------------------------------------------

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "test_compile_snippet_data")
GOLDEN_SUFFIX = ".py.snippet"

# case name -> a zero-argument builder of that case's snippet text. The house golden convention stores
# input+golden PAIRS because its inputs are source files; the inputs here are Python objects from
# ``kernel_snippet_samples``, so the directory holds goldens only and this table carries the binding.
# The goldens deliberately do not end in ``.py``: they are generated, non-conforming source.
GOLDEN_CASES = {
    # ``factory_full`` and ``factory_discovered_helpers`` build from the same factory and differ only in
    # emitted helper ORDER: passing ``kernel_body_func`` places ``add_infer_tileshape`` before the body,
    # discovering it places the body first. Both also carry the captured ``_SAMPLE_TILE`` constant.
    "factory_full": lambda: _factory_snippet(samples.create_add_kernel, samples.add_kernel_body),
    "factory_body_omitted": lambda: _factory_snippet(samples.create_add_kernel_inlined),
    "factory_discovered_helpers": lambda: _factory_snippet(samples.create_add_kernel),
    "factory_cross_module_helper": lambda: _factory_snippet(samples.create_add_kernel_cross_module),
    "factory_stdlib_alias": lambda: _factory_snippet(stdlib_forms.create_kernel_stdlib_alias),
    "jit_pinned_annotations": lambda: _direct_snippet(
        samples.direct_add_kernel_pinned, declared_annotations=_PINNED_ANNOTATIONS
    ),
    "jit_erased_annotations": lambda: _direct_snippet(samples.direct_add_kernel_erased),
    "jit_dotted_helpers": lambda: _direct_snippet(samples.direct_dotted_helper_kernel),
}


# Parametrized from the case table rather than from the directory, so every declared case is always
# compared and a missing golden fails instead of shrinking the parameter set.
@pytest.mark.parametrize("case", sorted(GOLDEN_CASES))
def test_snippet_matches_golden(case):
    path = os.path.join(DATA_DIR, case + GOLDEN_SUFFIX)
    assert os.path.exists(path), f"{case}{GOLDEN_SUFFIX} is missing; run render.py"
    with open(path, encoding="utf-8") as fh:
        golden = fh.read()
    compile(golden, case + GOLDEN_SUFFIX, "exec")
    assert GOLDEN_CASES[case]() == golden, (
        f"{case}{GOLDEN_SUFFIX} is out of sync with the emitter; run render.py"
    )


